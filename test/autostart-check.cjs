#!/usr/bin/env node
/*
 * 开机自启生成物检查（纯离线，不碰启动文件夹、不启动任何东西）。
 *
 * 为什么值得单独一个套件：
 *   自启项坏掉的表现是**登录时静默什么都不发生** —— 不报错、不留日志、没有退出码，
 *   用户只会觉得"开了自启怎么没起来"。这类故障没有任何运行时信号可抓，
 *   唯一能抓的地方就是"生成出来的那几个字节"。所以这里验的是字节，不是行为：
 *     · VBScript 字符串转义（`"` 要写成 `""`）—— 第一版写成 shell 风格，整行语法错误；
 *     · 纯 ASCII + CRLF + 无 BOM —— 与 小鸡开关.bat / xiaoji-launcher.vbs 同一条规矩；
 *     · 结构完整（Option Explicit 在前、End If 配对、最后一行是 sh.Run）。
 *
 * ⚠ 本套件**不执行** wscript：本机 wscript 被安全策略拦（Known Windows LOLBin），
 *   而且真跑起来会去拉起网关 —— 测试不该有这种副作用。
 *   代价是"能不能真起来"只能靠人工登录一次确认，这一点写进 docs/usage.md。
 */
const assert = require('node:assert')
const path = require('node:path')
const fs = require('node:fs')

const ROOT = path.dirname(__dirname)
const { buildVbs, vbsArg, port } = require(path.join(ROOT, 'scripts', 'autostart.cjs'))

let pass = 0
const fails = []
function check(name, fn) {
  try { fn(); pass++; console.log('  ✓ ' + name) }
  catch (e) { fails.push(name + ' :: ' + e.message); console.log('  ✗ ' + name + ' :: ' + e.message) }
}

const vbs = buildVbs()
const buf = Buffer.from(vbs, 'ascii')
const lines = vbs.split('\r\n')

console.log('\n[1] 字节卫生（wscript 对编码/行尾敏感）')

check('生成物是纯 ASCII（无中文注释混入）', () => {
  const bad = []
  for (let i = 0; i < buf.length; i++) if (buf[i] > 0x7e) bad.push(`${i}:0x${buf[i].toString(16)}`)
  assert.strictEqual(bad.length, 0, '出现非 ASCII 字节 ' + bad.slice(0, 5).join(','))
})

check('没有 BOM', () => {
  assert.ok(!(buf[0] === 0xef && buf[1] === 0xbb && buf[2] === 0xbf), '开头有 UTF-8 BOM')
})

check('全部是 CRLF，没有裸 LF', () => {
  const s = buf.toString('latin1')
  const crlf = (s.match(/\r\n/g) || []).length
  const lf = (s.match(/\n/g) || []).length
  assert.strictEqual(lf, crlf, `LF=${lf} 但 CRLF=${crlf}，存在裸 LF`)
  assert.ok(crlf > 10, 'CRLF 太少，可能整份被拼成一行')
})

console.log('\n[2] VBScript 语法骨架')

check('首行是注释，第二行也是注释（生成器指纹）', () => {
  assert.ok(/^'/.test(lines[0]), '首行不是注释: ' + lines[0])
  assert.ok(/Generated by scripts\/autostart\.cjs/.test(lines[0]), '缺少生成器指纹')
  assert.ok(/^'/.test(lines[1]), '第二行不是注释: ' + lines[1])
})

check('Option Explicit 出现在任何赋值之前', () => {
  const iOpt = lines.indexOf('Option Explicit')
  assert.ok(iOpt >= 0, '缺少 Option Explicit')
  const iFirstAssign = lines.findIndex((l) => /^\s*(Dim|Set|alive\s*=)/.test(l))
  assert.ok(iOpt < iFirstAssign, `Option Explicit 在第 ${iOpt + 1} 行，赋值在第 ${iFirstAssign + 1} 行`)
})

check('块级 If / End If 数量配平（单行 If 不算）', () => {
  // 单行 `If x Then y` 不需要 End If；只有以 Then 结尾的才开启一个块。
  const ifs = lines.filter((l) => /^\s*If\b/.test(l) && /\bThen\s*$/.test(l)).length
  const ends = lines.filter((l) => /^\s*End If\s*$/.test(l)).length
  assert.strictEqual(ifs, ends, `块级 If…Then=${ifs} 但 End If=${ends}`)
  const single = lines.filter((l) => /^\s*If\b/.test(l) && /\bThen\s+\S/.test(l)).length
  assert.ok(single >= 1, '一条单行 If 都没有？防重复启动那行应该是单行 If')
})

check('On Error Resume Next 与 On Error GoTo 0 配平', () => {
  const a = lines.filter((l) => l === 'On Error Resume Next').length
  const b = lines.filter((l) => l === 'On Error GoTo 0').length
  assert.strictEqual(a, b, `Resume Next=${a} GoTo 0=${b}`)
})

check('CreateObject 的对象都已 Dim', () => {
  const used = new Set()
  for (const l of lines) {
    const m = l.match(/Set\s+(\w+)\s*=\s*CreateObject/)
    if (m) used.add(m[1])
  }
  assert.ok(used.size >= 3, 'CreateObject 少于 3 处，自启逻辑不完整')
  for (const v of used) {
    assert.ok(lines.some((l) => new RegExp('^Dim\\b[^\\r\\n]*\\b' + v + '\\b').test(l)), `${v} 未在 Dim 里声明（Option Explicit 会直接报错）`)
  }
})

console.log('\n[3] 关键的那一行（错了就静默不启动）')

check('vbsArg 产出的是 VBScript 双引号转义，不是 shell 引号', () => {
  assert.strictEqual(vbsArg('C:\\a\\b.vbs'), '""C:\\a\\b.vbs""')
  assert.strictEqual(vbsArg('say "hi"'), '""say hi""', '内层引号应被剥掉，而不是转义成 \\"')
})

check('sh.Run 行形状正确：三个参数、窗口隐藏、不等待', () => {
  const run = lines.find((l) => l.startsWith('sh.Run '))
  assert.ok(run, '找不到 sh.Run 行')
  // sh.Run "wscript.exe ""P1"" ""P2"" ""P3""", 0, False
  const re = /^sh\.Run "wscript\.exe ""[^"]+"" ""[^"]+"" ""[^"]+""", 0, False$/
  assert.ok(re.test(run), '形状不对: ' + run)
})

check('sh.Run 的三个路径分别是 launcher / node / server，且都是绝对路径', () => {
  const run = lines.find((l) => l.startsWith('sh.Run '))
  const args = [...run.matchAll(/""([^"]+)""/g)].map((m) => m[1])
  assert.strictEqual(args.length, 3, '参数个数不是 3: ' + args.length)
  const [launcher, node, server] = args
  assert.ok(/xiaoji-launcher\.vbs$/i.test(launcher), 'launcher 不对: ' + launcher)
  assert.ok(/node(\.exe)?$/i.test(node), 'node 不对: ' + node)
  assert.ok(/server\.mjs$/i.test(server), 'server 不对: ' + server)
  for (const p of args) assert.ok(/^[A-Za-z]:\\/.test(p), '不是绝对 Windows 路径: ' + p)
})

check('sh.Run 在文件末尾（前面任何一句报错都不该拦住它）', () => {
  const iRun = lines.findIndex((l) => l.startsWith('sh.Run '))
  const after = lines.slice(iRun + 1).filter((l) => l.trim() !== '')
  assert.strictEqual(after.length, 0, 'sh.Run 之后还有语句: ' + after.join(' | '))
})

console.log('\n[4] 幂等 / 防撞端口')

check('已经活着就 Quit，不重复启动', () => {
  const iAlive = lines.findIndex((l) => /^If alive Then WScript\.Quit 0$/.test(l))
  const iRun = lines.findIndex((l) => l.startsWith('sh.Run '))
  assert.ok(iAlive >= 0, '缺少 `If alive Then WScript.Quit 0`')
  assert.ok(iAlive < iRun, 'Quit 出现在 sh.Run 之后，等于没防重复启动')
})

check('健康检查用的是 config.json 里的端口', () => {
  assert.ok(vbs.includes(`http://127.0.0.1:${port()}/healthz`), 'VBS 里的端口与 config.json 不一致')
})

check('健康检查有超时（否则网络栈卡住会一直挂到登录卡死）', () => {
  assert.ok(/http\.SetTimeouts \d+, \d+, \d+, \d+/.test(vbs), '缺少 SetTimeouts')
})

console.log('\n[5] 痕迹日志（没有它就无法区分"跑过"和"从没跑过"）')

check('会往 logs/autostart.log 追加一行', () => {
  const m = vbs.match(/OpenTextFile\("([^"]+)", 8, True\)/)
  assert.ok(m, '找不到 OpenTextFile 追加写')
  assert.ok(/logs\\autostart\.log$/.test(m[1]), '日志路径不对: ' + m[1])
  assert.ok(lines.some((l) => /ts\.WriteLine Now & "  alive=" & alive/.test(l)), '没有写内容')
})

check('日志路径里的反斜杠没有被重复转义', () => {
  const m = vbs.match(/OpenTextFile\("([^"]+)", 8, True\)/)
  assert.ok(!/\\\\/.test(m[1]), '出现双反斜杠: ' + m[1])
})

console.log('\n[6] 已安装的那一份是否与当前生成器一致')

check('启动项若已安装，字节必须与 buildVbs() 一致（防止装了旧的坏版本）', () => {
  const { linkPath } = require(path.join(ROOT, 'scripts', 'autostart.cjs'))
  const f = linkPath()
  if (!fs.existsSync(f)) { console.log('    · 未安装，跳过'); return }
  const disk = fs.readFileSync(f)
  const want = Buffer.from(vbs, 'ascii')
  if (disk.equals(want)) return
  const d = disk.toString('ascii').split('\r\n')
  const w = want.toString('ascii').split('\r\n')
  const i = d.findIndex((l, k) => l !== w[k])
  throw new Error(`已安装的与当前生成物不同（首个差异在第 ${i + 1} 行）\n      磁盘: ${d[i]}\n      期望: ${w[i]}\n      → 跑 node scripts/autostart.cjs install 重新生成`)
})

console.log(`\n${pass} passed, ${fails.length} failed`)
if (fails.length) {
  console.log('\n失败项:')
  fails.forEach((f) => console.log('  · ' + f))
  process.exit(1)
}
