#!/usr/bin/env node
/*
 * 开机自启（Windows，登录时启动）。
 *
 * 用法：
 *   node scripts/autostart.cjs install     写入启动项
 *   node scripts/autostart.cjs uninstall   移除启动项
 *   node scripts/autostart.cjs status      看当前状态
 *
 * 为什么用「启动文件夹」而不是计划任务：
 *   ① 计划任务要 schtasks.exe，它常被杀软/安全策略拦（本机实测直接被拦下），
 *      而"装不上"的表现是用户以为开了自启、其实没开 —— 比没有这个功能更糟；
 *   ② 启动文件夹只是一个文件，**不需要管理员权限**，卸载就是删掉它，
 *      用户能在资源管理器里亲眼看到"自启项是什么"，符合本项目"可解释优先"的取向；
 *   ③ 计划任务默认跑在"是否登录"的语义里，容易变成会话 0 的 SYSTEM 进程，
 *      那会把 config.json 写成 SYSTEM 所有 —— 之后用户自己双击开关反而写不进去。
 *   代价：只在**登录后**启动，不是"开机就起、登录前就可用"。本工具是本机自用网关，
 *   没有服务端语义，这个差别不影响使用。
 *
 * 启动项本身是一个 .vbs：
 *   · 先探 /healthz，已经活着就什么都不做（避免重复启动撞端口）；
 *   · 没活着就通过 xiaoji-launcher.vbs 隐藏启动（无黑窗口）。
 *   刻意保持**纯 ASCII + CRLF** —— 与 小鸡开关.bat / xiaoji-launcher.vbs 同一条规矩，
 *   避免 wscript/cmd 在 GBK 环境下把中文读坏（startup-files-check.cjs 管的是仓库里那两个文件，
 *   这份是生成到用户目录的，但坑是同一个，所以这里自觉遵守）。
 */
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')

const ROOT = path.dirname(__dirname)
const SERVER = path.join(ROOT, 'server.mjs')
const LAUNCHER = path.join(ROOT, 'xiaoji-launcher.vbs')
const NODE = process.execPath
const LINK_NAME = 'xiaoji-free-model.vbs'
// 启动项的执行痕迹。VBS 里写它，status 里读它 —— 用来回答"自启到底跑过没"。
// ⚠ 路径直接嵌进 VBS 字符串，**不要**转义反斜杠：VBScript 字符串里没有转义字符，
//   多写一层会把路径变成 C:\\Users\\...（Windows 能容忍，但没必要且难读）。
const LOG = path.join(ROOT, 'logs', 'autostart.log')

function startupDir() {
  // %APPDATA%\Microsoft\Windows\Start Menu\Programs\Startup
  const appData = process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming')
  return path.join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup')
}
const linkPath = () => path.join(startupDir(), LINK_NAME)

function port() {
  try { return Number(JSON.parse(fs.readFileSync(path.join(ROOT, 'config.json'), 'utf8')).port) || 8787 } catch { return 8787 }
}

// ⚠ 这里是**VBScript 字符串字面量**里的转义，不是 shell 引号：`"` 要写成 `""`。
//   第一版按 shell 习惯写成 `"path"`，生成出来的那行是
//     sh.Run "wscript.exe "C:\...\launcher.vbs" ...", 0, False
//   —— VBScript 语法错误，**登录时静默失败**，用户以为开了自启其实没开。
//   这类错误没法靠"文件存在"发现，只能靠盯生成物（所以 install 之后要复核内容）。
const vbsArg = (s) => '""' + String(s).replace(/"/g, '') + '""'

function buildVbs() {
  const p = port()
  const lines = [
    "' XiaoJi Free Model - auto start at logon. Generated by scripts/autostart.cjs",
    "' To disable: run  node scripts/autostart.cjs uninstall  (or just delete this file).",
    'Option Explicit',
    'Dim sh, http, alive',
    'alive = False',
    'On Error Resume Next',
    'Set http = CreateObject("WinHttp.WinHttpRequest.5.1")',
    'If Err.Number = 0 Then',
    '  http.SetTimeouts 1500, 1500, 1500, 1500',
    `  http.Open "GET", "http://127.0.0.1:${p}/healthz", False`,
    '  http.Send',
    '  If Err.Number = 0 Then',
    '    If http.Status = 200 Then alive = True',
    '  End If',
    'End If',
    'Err.Clear',
    'On Error GoTo 0',
    "' Trace: record when this ran and whether the gateway was already alive.",
    "' Why it matters: a broken startup item fails SILENTLY (nothing happens at logon),",
    "' so without a trace there is no way to tell 'it worked' from 'it never ran'.",
    'On Error Resume Next',
    'Dim fso, ts',
    'Set fso = CreateObject("Scripting.FileSystemObject")',
    `Set ts = fso.OpenTextFile("${LOG}", 8, True)`,
    'If Err.Number = 0 Then',
    '  ts.WriteLine Now & "  alive=" & alive',
    '  ts.Close',
    'End If',
    'Err.Clear',
    'On Error GoTo 0',
    "' Already running (started by hand / another session) -> do nothing.",
    'If alive Then WScript.Quit 0',
    'Set sh = CreateObject("WScript.Shell")',
    `sh.Run "wscript.exe ${vbsArg(LAUNCHER)} ${vbsArg(NODE)} ${vbsArg(SERVER)}", 0, False`,
    '',
  ]
  return lines.join('\r\n')
}

function check() {
  const problems = []
  if (process.platform !== 'win32') problems.push(`当前系统是 ${process.platform}；本脚本只处理 Windows（Linux/容器请用 systemd 或 Docker restart 策略）`)
  if (!fs.existsSync(SERVER)) problems.push(`找不到 ${SERVER}`)
  if (!fs.existsSync(LAUNCHER)) problems.push(`找不到 ${LAUNCHER}（隐藏启动要靠它，缺了会弹出黑窗口）`)
  if (!fs.existsSync(NODE)) problems.push(`找不到 node: ${NODE}`)
  return problems
}

function install() {
  const bad = check()
  if (bad.length) { bad.forEach((b) => console.error('✗ ' + b)); process.exit(1) }
  const body = buildVbs()
  // 自检: 这一行是**唯一**决定"能不能起来"的地方，而且错了也不会报错（登录时静默不启动）。
  // 判据就两条：外层字符串以 `"wscript.exe ""` 开头、整行以 `"` 收尾。
  const runLine = body.split('\r\n').find((l) => l.startsWith('sh.Run ')) || ''
  if (!/^sh\.Run "wscript\.exe ""/.test(runLine) || !/"\s*,\s*0,\s*False$/.test(runLine)) {
    console.error('✗ 生成内容自检失败（sh.Run 的引号转义不对），已中止，未写入任何文件')
    console.error('  实际生成: ' + runLine)
    process.exit(1)
  }
  const dir = startupDir()
  fs.mkdirSync(dir, { recursive: true })
  // 痕迹日志所在目录要先存在：VBS 里 OpenTextFile 的第 3 个参数只管"文件不存在就建"，
  // **不管"目录不存在就建"** —— 目录缺了它会静默跳过（外面套着 On Error Resume Next）。
  fs.mkdirSync(path.dirname(LOG), { recursive: true })
  // ⚠ 必须用 Buffer + 显式 CRLF，且不写 BOM —— wscript 对 BOM 的处理各版本不一致，
  //   而 CRLF 是 VBScript 行尾的硬要求（纯 LF 在部分环境会把整行当注释吞掉）。
  fs.writeFileSync(linkPath(), Buffer.from(body, 'ascii'))
  console.log('✓ 已写入启动项：' + linkPath())
  console.log('  启动方式：登录后检查 http://127.0.0.1:' + port() + '/healthz，不通才启动（隐藏窗口）')
  console.log('  取消自启：node scripts/autostart.cjs uninstall')
}

function uninstall() {
  const f = linkPath()
  if (!fs.existsSync(f)) { console.log('· 当前没有自启项，无需移除'); return }
  fs.unlinkSync(f)
  console.log('✓ 已移除启动项：' + f)
}

function status() {
  const f = linkPath()
  if (!fs.existsSync(f)) { console.log('自启：未启用'); return }
  const t = fs.readFileSync(f, 'ascii')
  const portLine = (t.match(/http:\/\/127\.0\.0\.1:(\d+)\/healthz/) || [])[1] || '?'
  console.log('自启：已启用')
  console.log('  文件：' + f)
  console.log('  健康检查端口：' + portLine + (Number(portLine) === port() ? '（与 config.json 一致）' : `（⚠ 与 config.json 的 ${port()} 不一致，重新 install 可修正）`))
  console.log('  启动器：' + (fs.existsSync(LAUNCHER) ? 'xiaoji-launcher.vbs 存在' : '⚠ 缺失'))
}

// 供 test/autostart-check.cjs 直接 require：只取 buildVbs 验生成物，不碰启动文件夹。
module.exports = { buildVbs, startupDir, linkPath, port, vbsArg }

if (require.main === module) {
  const cmd = (process.argv[2] || 'status').toLowerCase()
  if (cmd === 'install') install()
  else if (cmd === 'uninstall') uninstall()
  else if (cmd === 'status') status()
  else { console.error('用法: node scripts/autostart.cjs [install|uninstall|status]'); process.exit(2) }
}
